/**
 * ========== 구현할 함수 (매일 지우고 새로 구현 연습) ==========
 *
 *   sort(arr)
 *
 * ---------------------------------------------------------------------------
 * 퀵소트 (Quick Sort)
 * ---------------------------------------------------------------------------
 * - 파티션: pivot 기준으로 왼쪽은 pivot 이하, 오른쪽은 pivot 초과.
 * - 재귀: pivot 왼쪽 구간·오른쪽 구간 각각 퀵소트.
 * - pivot 선택: 첫 원소 / 마지막 / 중간 / 랜덤 등 자유.
 * - 재귀 종료: 구간 길이가 0 또는 1이면 더 이상 나누지 않음.
 *
 * ---------------------------------------------------------------------------
 * sort(arr)
 * ---------------------------------------------------------------------------
 * - 시그니처: sort(arr: number[]): number[]
 * - 반환: 오름차순 정렬된 새 배열.
 * - 인자 arr은 수정하지 않음 (원본 불변).
 *
 * =============================================================
 */
